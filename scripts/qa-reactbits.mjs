import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import sharp from 'sharp';
const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
const errors=[];
for(const width of [1440,390]){
 const page=await browser.newPage({viewport:{width,height:900}});
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error') errors.push(m.text())});
 await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'});
 await page.waitForFunction(()=>document.querySelector('.rb-aurora canvas') || document.querySelector('.rb-aurora')?.dataset.fallback);
 assert.equal(await page.locator('[data-react-bits="ScrollFloat"]').count(),2);
 assert.equal(await page.locator('[data-react-bits="Magnet"]').count(),1);
 const bounds=await page.evaluate(async()=>{
  const {ScrollTrigger}=await import('/src/animations/engine.ts');
  return Object.fromEntries(['cinema','estudio'].map(id=>{const t=ScrollTrigger.getById(id);return [id,{start:t.start,end:t.end}]}));
 });
 const seek=async(id,p)=>{
  await page.evaluate(y=>scrollTo(0,y),bounds[id].start+(bounds[id].end-bounds[id].start)*p);
  await page.waitForTimeout(180);
 };
 const aurora=page.locator('.rb-aurora');
 await seek('cinema',1.5/28);
 const frame=await aurora.getAttribute('data-frame-time');
 assert(frame && Math.abs(Number(frame)-1.5)<.01,'Aurora receives GSAP time');
 await page.waitForTimeout(250);
 assert.equal(await aurora.getAttribute('data-frame-time'),frame,'Aurora does not autoplay');
 await page.screenshot({path:'artifacts/qa-cinema/reactbits-hero-'+width+'.png'});
 await seek('cinema',3/28);
 assert.notEqual(await aurora.getAttribute('data-frame-time'),frame);
 await seek('cinema',1.5/28);
 assert.equal(await aurora.getAttribute('data-frame-time'),frame,'Aurora reverses');
 const chars=()=>page.locator('.rb-float-char').evaluateAll(nodes=>nodes.map(n=>getComputedStyle(n).transform));
 await seek('estudio',.16);
 const first=await chars();
 await seek('estudio',.8);
 assert.notDeepEqual(await chars(),first);
 await page.screenshot({path:'artifacts/qa-cinema/reactbits-studio-'+width+'.png'});
 await seek('estudio',.16);
 assert.deepEqual(await chars(),first,'ScrollFloat reverses');
 const spacing=await page.locator('.rb-float-char').last().evaluate(n=>getComputedStyle(n).paddingLeft);
 assert.equal(spacing,'0px');
 await page.locator('.contact-magnet').scrollIntoViewIfNeeded();
 const box=await page.locator('.contact-magnet').boundingBox();
 await page.mouse.move(box.x+box.width*.75,box.y+box.height*.5);
 await page.waitForTimeout(400);
 const moved=await page.locator('.contact-magnet > div').evaluate(n=>getComputedStyle(n).transform);
 assert.notEqual(moved,'matrix(1, 0, 0, 1, 0, 0)');
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.waitForFunction(()=>document.querySelectorAll('.pin-spacer').length===0&&document.querySelectorAll('.rb-aurora canvas').length===0);
 await page.waitForTimeout(550);
 assert.equal(await page.locator('.contact-magnet > div').evaluate(n=>getComputedStyle(n).transform),'matrix(1, 0, 0, 1, 0, 0)');
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.emulateMedia({reducedMotion:'no-preference'});
 await page.waitForFunction(()=>document.querySelectorAll('.rb-aurora canvas').length===1);
 await page.close();
}
await browser.close();
assert.deepEqual(errors,[]);
const files=['reactbits-hero-1440','reactbits-studio-1440','reactbits-hero-390','reactbits-studio-390'];
const parts=[];
for(let i=0;i<files.length;i++)parts.push({input:await sharp('artifacts/qa-cinema/'+files[i]+'.png').resize(540,338,{fit:'contain',background:'#090b0b'}).toBuffer(),left:i%2*540,top:Math.floor(i/2)*338});
await sharp({create:{width:1080,height:676,channels:3,background:'#090b0b'}}).composite(parts).jpeg({quality:85}).toFile('artifacts/qa-cinema/reactbits-review.jpg');
console.log('React Bits: Aurora WebGL rendering, scroll sync/reversal, no autoplay; ScrollFloat reversal; Magnet movement; reduced-motion cleanup passed on desktop/mobile.');